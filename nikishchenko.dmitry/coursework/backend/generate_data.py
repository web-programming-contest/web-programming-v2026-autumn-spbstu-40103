def build_goods() -> list[dict]:
    rng = random.Random(2024)
    base = date(2024, 7, 31)
    goods = []
    for gid, name, price, gtype, color, desc, specs in ARCHIVE:
        is_hit = gid in ARCHIVE_HITS
        goods.append({
            "id": gid, "name": name, "price": price, "oldPrice": None,
            "rating": round(rng.uniform(3.8, 5.0), 1),
            "type": gtype, "color": color,
            "isNew": False, "isHit": is_hit,
            "popularity": rng.randint(80, 89) if is_hit else rng.randint(15, 85),
            "createdAt": (base - timedelta(days=rng.randint(15, 300))).isoformat(),
            "image": f"/images/goods/image_{gid}.png",
            "description": desc,
            "specs": [{"name": "Гарантия", "value": "1 год"}] + [{"name": n, "value": v} for n, v in specs],
        })
    for (gid, name, price, old, rating, gtype, color, is_new, is_hit, pop, created, desc, specs) in MOCKUP:
        goods.append({
            "id": gid, "name": name, "price": price, "oldPrice": old, "rating": rating,
            "type": gtype, "color": color, "isNew": is_new, "isHit": is_hit,
            "popularity": pop, "createdAt": created,
            "image": f"/images/goods/image_{gid}.png",
            "description": desc,
            "specs": [{"name": "Гарантия", "value": "1 год"}] + [{"name": n, "value": v} for n, v in specs],
        })
    return goods


def dump(name: str, data) -> None:
    (DATA / name).write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    reset = "--reset" in sys.argv
    DATA.mkdir(exist_ok=True)

    goods = build_goods()
    assert len({g["id"] for g in goods}) == len(goods), "повторяющиеся id"
    dump("goods.json", goods)
    print(f"goods.json: {len(goods)} товаров")

    if reset or not (DATA / "users.json").exists():
        salt, pwd_hash = hash_password(DEFAULT_PASSWORD)
        dump("users.json", [{"login": DEFAULT_LOGIN, "salt": salt, "hash": pwd_hash}])
        print(f"users.json: пользователь {DEFAULT_LOGIN} / {DEFAULT_PASSWORD}")

    if reset or not (DATA / "orders.json").exists():
        dump("orders.json", [
            {"id": oid, "login": DEFAULT_LOGIN, "date": d, "items": [], "itemsCount": cnt, "total": total,
             "email": None, "phone": None, "delivery": "pickup", "address": None,
             "payment": "card", "packaging": False}
            for oid, d, cnt, total in SEED_ORDERS
        ])
        print(f"orders.json: {len(SEED_ORDERS)} стартовых заказа")


if __name__ == "__main__":
    main()
